export function createCardFrontTexture(card) {
  if (cardTextureCache[card.uid]) return cardTextureCache[card.uid];

  const c = document.createElement('canvas');
  c.width = CARD_W;
  c.height = CARD_H;
  const ctx = c.getContext('2d');
  ctx.scale(SCALE_X, SCALE_Y);

  const isMajor = card.suit === 'Major';
  const majId = isMajor ? parseInt(card.uid.replace('M_', ''), 10) : -1;
  const palette = isMajor ? (MAJOR_PALETTES[majId] || MAJOR_PALETTES[0]) : (SUIT_PALETTES[card.suit] || SUIT_PALETTES.Wands);

  drawCardBaseMargin(ctx);

  // Clip scene art inside the central stained-glass window (x=20..236, y=20..286)
  ctx.save();
  ctx.beginPath();
  ctx.rect(20, 20, 216, 266);
  ctx.clip();

  const skipHills = !isMajor && !['Page', 'Knight'].includes(card.name.split(' ')[0]);
  drawLowPolyBackdrop(ctx, palette, card.uid, !skipHills);

  if (isMajor) {
    drawMajorArcanaScene(ctx, majId);
  } else {
    drawMinorArcanaScene(ctx, card);
  }
  ctx.restore();

  const topLabel = isMajor
    ? `ARCANA · ${ROMAN[majId] || majId}`
    : `${card.name.split(' ')[0].toUpperCase()} · ${card.suit.toUpperCase()}`;
  drawCardFrameAndCartouche(ctx, card, topLabel);

const tex = new THREE.CanvasTexture(c);
  tex.colorSpace = THREE.SRGBColorSpace;
  cardTextureCache[card.uid] = tex;
  return tex;
}

const cardDataUrlCache = {};

export function getCardFrontDataURL(card) {
  if (!card?.uid) return '';
  if (cardDataUrlCache[card.uid]) return cardDataUrlCache[card.uid];
  const tex = createCardFrontTexture(card);
  const url = tex?.image?.toDataURL ? tex.image.toDataURL('image/png') : '';
  if (url) cardDataUrlCache[card.uid] = url;
  return url;
}
